# Example 02 – Variables & Data Types
# Python has several built-in data types.

# String
name = "Alice"

# Integer
age = 25

# Float
height = 5.7

# Boolean
is_student = True

# Print all variables
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is student:", is_student)

# f-string (modern way to format strings)
print(f"{name} is {age} years old and {height} ft tall.")
